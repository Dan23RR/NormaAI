"""The report of a document check as a PDF, headed with the organisation's letterhead.

What ``report.render_html`` shows, in the same order and with the same words:
the document, the day of the check and the texts it was made on, the date of
the document, the four counts; a card for every finding to correct or to check
(where it is in the document, the quotes, the outcome, the official text, the
differences word by word between the text then and now, the link to the text in
force); the table of what is fine; the table of the acts the check does not
read; the articles of the document itself; the notes on the sources and the
credit to Normattiva. Two things only the PDF says: every card and every row of
what is fine names the text it was compared with ("testo consolidato al
27/07/2026"), and the heading gives the day of the last re-check, so that a
client who reads the PDF months later knows the date of the law it speaks of.

The letterhead (``src/reports/letterhead.py``) heads the first page: logo, name
of the practice, address, contacts. The other pages carry its name in small.
NormaAI appears only in small at the foot of every page, after the note of the
practice when it has one and the page number.

Differences: a removed word is struck through in red, an added word is
underlined in green, so that they still read apart on a printout in black and
white; a line under the counts says so when the PDF has any.

Fonts: DejaVu Sans, vendored with the gap-analysis reports in
``src/reports/fonts``, for the accents, «», ’ and “”. Without the files the PDF
falls back to Helvetica with those characters spelled in Latin-1, as
``src/reports/generator.py`` does.

No marking of AI-generated content. The gap-analysis PDFs say on every page and
in their metadata that an AI system generated them (AI Act art. 50(2)), because
a language model writes them. The document check calls no model: its outcomes
come from rules written by people (patterns that find the references,
comparison of the words with the official text, differences word by word),
which recital 12 of the AI Act leaves out of the definition of an AI system,
and its words are the document's, the law's and fixed sentences. Marking it as
generated by AI would be false. The metadata name the practice (Author) and the
software (Creator).
"""

