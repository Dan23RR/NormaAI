def render_pdf(
    check: DocumentCheck,
    letterhead: Letterhead,
    *,
    rechecked_on: str | None = None,
    now: datetime | None = None,
) -> bytes:
    """The PDF of a check, headed with ``letterhead``. ``rechecked_on``: ISO date of the last re-check."""
    document = check.document or "Documento"
    pdf = _ReportPDF(letterhead, document)
    pdf.set_title(f"Controllo del documento: {document}")
    pdf.set_author(letterhead.name)
    pdf.set_subject(KICKER)
    pdf.set_creator("NormaAI")
    pdf.set_lang("it")
    pdf.set_creation_date((now or datetime.now(UTC)).replace(microsecond=0))
    pdf.add_page()

    groups = {name: check.group(name) for name in GROUPS}
    _heading(pdf, check, rechecked_on)
    _summary(pdf, {name: len(found) for name, found in groups.items()})
    if any(f.before or (f.altered_quote and f.official_quote) for f in check.findings):
        _paragraph(pdf, DIFF_LEGEND, size=8, color=_MUTED, line=4)
    if not check.findings:
        _paragraph(pdf, NO_REFERENCES)
    for name in ("correggere", "controllare"):
        if groups[name]:
            _section_title(pdf, GROUP_TITLES[name], name)
            for finding in groups[name]:
                _card(pdf, finding)
    if groups["a_posto"]:
        _section_title(pdf, GROUP_TITLES["a_posto"], "a_posto")
        _fine_table(pdf, groups["a_posto"])
    if groups["non_coperto"]:
        _section_title(pdf, GROUP_TITLES["non_coperto"], "non_coperto")
        _paragraph(pdf, NOT_READ_INTRO)
        _not_read_table(pdf, groups["non_coperto"])
    if check.own_articles:
        _section_title(pdf, OWN_ARTICLES_TITLE, "non_coperto")
        _paragraph(pdf, OWN_ARTICLES_INTRO)
        for ref in check.own_articles:
            pdf.font("", _BODY)
            pdf.set_x(pdf.l_margin + 1)
            pdf.cell(4, _LINE, "•")
            pdf.multi_cell(
                pdf.epw - 5,
                _LINE,
                f"Riga {ref.line}: {ref.raw}",
                align="L",
                new_x="LMARGIN",
                new_y="NEXT",
            )
    _notes(pdf)
    return bytes(pdf.output())
