def _not_read_table(pdf: _ReportPDF, findings: list[Finding]) -> None:
    _table(
        pdf,
        ["Riga", "Nel documento", "Norma", "Perché"],
        (12, 44, 52, 66),
        [
            [
                (str(f.reference.line), None),
                (f.reference.raw, None),
                (_title(f), f.url),
                (" ".join(f.messages), None),
            ]
            for f in findings
        ],
    )


def _notes(pdf: _ReportPDF) -> None:
    _room(pdf, 40)
    pdf.ln(4)
    pdf.set_draw_color(*_RULE)
    pdf.set_line_width(0.2)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - _MARGIN, pdf.get_y())
    pdf.ln(3)
    for text in (_FOOTER, _FOOTER_ITALIAN):
        _paragraph(pdf, text, size=8, color=_MUTED, line=3.9)
    _runs(
        pdf,
        [
            (text, "U" if link else "", _LINK if link else _MUTED, link)
            for text, link in credit_runs()
        ],
        size=8,
        line=3.9,
    )


